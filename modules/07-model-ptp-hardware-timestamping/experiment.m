%% P07 - Model PTP Hardware Timestamping
experimentFigureTag = 'P07ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the capture-plane mechanism before looking at syntax
disp('What inputs, observable effects, and failure modes matter when you model PTP Hardware Timestamping?');
disp(['P06 exposed four-timestamp offset and round-trip arithmetic. P07 keeps that arithmetic ' ...
    'visible and moves each timestamp toward or away from the modeled wire reference plane.']);
disp(['Mechanism: if captured timestamp i has error e_i, offset gains ' ...
    '(e2-e1+e3-e4)/2 and round trip gains e4-e1-e3+e2.']);

%% Visualize the deterministic baseline estimates
baseline = model(100000,120,800,800,4000,1,8,1);
fprintf(['Baseline true follower-minus-leader offset = %.0f ns. Software capture mean = %.2f ns ' ...
    'with %.0f ns peak-to-peak; hardware capture mean = %.2f ns with %.0f ns peak-to-peak.\n'], ...
    baseline.clockOffsetNs,baseline.softwareMeanClockOffsetEstimateNs, ...
    baseline.softwareOffsetPeakToPeakNs,baseline.hardwareMeanClockOffsetEstimateNs, ...
    baseline.hardwareOffsetPeakToPeakNs);
fprintf(['The 8 ns teaching tick bounds each hardware stamp quantization error to %.0f ns. ' ...
    'These are analytical timestamps, not measurements from a NIC or clock.\n'], ...
    baseline.hardwareQuantizationPerStampBoundNs);

figure('Name','P07 baseline offset estimates by capture plane', ...
    'Tag',experimentFigureTag);
plot(baseline.exchangeIndex,baseline.softwareEstimatedClockOffsetNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Host-stack software capture'); hold on;
plot(baseline.exchangeIndex,baseline.hardwareEstimatedClockOffsetNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Corrected near-wire hardware capture');
yline(baseline.clockOffsetNs,'k--','LineWidth',1.2, ...
    'DisplayName','Simulated true offset');
hold off; grid on;
xlabel('Deterministic exchange index');
ylabel('Estimated follower-minus-leader offset (ns)');
title('Baseline view 1: timestamp placement changes offset error');
legend('Location','best');

expectedSoftwareOffsetNs = [170 320 120 270 220 70 420 120];
expectedHardwareOffsetNs = [118 118 122 118 122 122 118 122];
assert(isequal(baseline.softwareEstimatedClockOffsetNs, ...
        expectedSoftwareOffsetNs) && ...
    isequal(baseline.hardwareEstimatedClockOffsetNs, ...
        expectedHardwareOffsetNs), ...
    'Baseline capture-plane offset estimates changed.');

%% Change the view to per-event timestamp placement error
eventLabels = {'T1 leader TX';'T2 follower RX'; ...
    'T3 follower TX';'T4 leader RX'};
firstExchangeErrorsNs = [baseline.softwareTimestampPlacementErrorNs(:,1), ...
    baseline.hardwareTimestampErrorNs(:,1)];
figure('Name','P07 baseline timestamp placement errors', ...
    'Tag',experimentFigureTag);
bar(1:4,firstExchangeErrorsNs); grid on;
set(gca,'XTick',1:4,'XTickLabel',eventLabels,'XTickLabelRotation',18);
xlabel('Timestamp event and modeled capture plane');
ylabel('Captured timestamp minus reference-plane timestamp (ns)');
title('Baseline view 2: host-path error versus corrected tick error');
legend({'Software placement','Hardware after correction'},'Location','best');

expectedSoftwareRoundTripNs = [4500 4800 4800 5100 5000 5100 5200 4800];
expectedHardwareRoundTripNs = [1596 1596 1604 1596 1604 1604 1596 1604];
assert(isequal(firstExchangeErrorsNs,[-600 4;900 0;-700 4;700 4]) && ...
    isequal(baseline.softwareEstimatedRoundTripDelayNs, ...
        expectedSoftwareRoundTripNs) && ...
    isequal(baseline.hardwareEstimatedRoundTripDelayNs, ...
        expectedHardwareRoundTripNs), ...
    'Baseline placement errors or round-trip estimates changed.');
assert(all(baseline.idealOffsetIdentityResidualNs == 0) && ...
    all(baseline.softwareOffsetIdentityResidualNs == 0) && ...
    all(baseline.hardwareOffsetIdentityResidualNs == 0) && ...
    baseline.hardwareQuantizationBoundSatisfied, ...
    'Baseline timestamp-error identities or quantization bounds changed.');

%% Sweep 1 - change only host timestamp-path latency scale
hostLatencyScales = [0 1 2];
softwareSweepOffsetRangeNs = zeros(size(hostLatencyScales));
hardwareSweepOffsetRangeNs = zeros(size(hostLatencyScales));
softwareSweepMaxAbsOffsetErrorNs = zeros(size(hostLatencyScales));
hardwareSweepMaxAbsOffsetErrorNs = zeros(size(hostLatencyScales));
softwareSweepMaxAbsRoundTripErrorNs = zeros(size(hostLatencyScales));
hardwareSweepMaxAbsRoundTripErrorNs = zeros(size(hostLatencyScales));
for sweepIndex = 1:numel(hostLatencyScales)
    swept = model(100000,120,800,800,4000, ...
        hostLatencyScales(sweepIndex),8,1);
    softwareSweepOffsetRangeNs(sweepIndex) = ...
        swept.softwareOffsetPeakToPeakNs;
    hardwareSweepOffsetRangeNs(sweepIndex) = ...
        swept.hardwareOffsetPeakToPeakNs;
    softwareSweepMaxAbsOffsetErrorNs(sweepIndex) = ...
        swept.softwareMaxAbsClockOffsetErrorNs;
    hardwareSweepMaxAbsOffsetErrorNs(sweepIndex) = ...
        swept.hardwareMaxAbsClockOffsetErrorNs;
    softwareSweepMaxAbsRoundTripErrorNs(sweepIndex) = ...
        swept.softwareMaxAbsRoundTripErrorNs;
    hardwareSweepMaxAbsRoundTripErrorNs(sweepIndex) = ...
        swept.hardwareMaxAbsRoundTripErrorNs;
end

figure('Name','P07 host-path latency sweep offset spread', ...
    'Tag',experimentFigureTag);
plot(hostLatencyScales,softwareSweepOffsetRangeNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Software offset peak-to-peak'); hold on;
plot(hostLatencyScales,hardwareSweepOffsetRangeNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Hardware offset peak-to-peak');
hold off; grid on;
xlabel('Host timestamp-path latency scale (dimensionless)');
ylabel('Offset estimate peak-to-peak (ns)');
title('Sweep 1: host-path variation remains outside near-wire capture');
legend('Location','best');

figure('Name','P07 host-path latency sweep round-trip error', ...
    'Tag',experimentFigureTag);
plot(hostLatencyScales,softwareSweepMaxAbsRoundTripErrorNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Software max absolute error'); hold on;
plot(hostLatencyScales,hardwareSweepMaxAbsRoundTripErrorNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Hardware max absolute error');
hold off; grid on;
xlabel('Host timestamp-path latency scale (dimensionless)');
ylabel('Maximum absolute round-trip error (ns)');
title('Sweep 1 changed view: capture plane controls included latency');
legend('Location','best');

assert(isequal(softwareSweepOffsetRangeNs,[0 350 700]) && ...
    isequal(hardwareSweepOffsetRangeNs,[4 4 4]) && ...
    isequal(softwareSweepMaxAbsOffsetErrorNs,[0 300 600]) && ...
    isequal(hardwareSweepMaxAbsOffsetErrorNs,[2 2 2]), ...
    'Host-path latency sweep offset metrics changed.');
assert(isequal(softwareSweepMaxAbsRoundTripErrorNs,[0 3600 7200]) && ...
    isequal(hardwareSweepMaxAbsRoundTripErrorNs,[4 4 4]), ...
    'Host-path latency sweep round-trip metrics changed.');
disp(['Mechanism: software stamps bracket modeled host TX/RX paths, so their latency pattern ' ...
    'enters e_i. Near-wire hardware stamps are outside that lever.']);

%% Sweep 2 - reset host scale and change only hardware tick size
hardwareTicksNs = [1 8 64];
hardwareTickSweepOffsetRangeNs = zeros(size(hardwareTicksNs));
hardwareTickSweepMaxAbsOffsetErrorNs = zeros(size(hardwareTicksNs));
hardwareTickSweepRoundTripRangeNs = zeros(size(hardwareTicksNs));
hardwareTickSweepMaxAbsRoundTripErrorNs = zeros(size(hardwareTicksNs));
softwareTickSweepOffsetRangeNs = zeros(size(hardwareTicksNs));
for sweepIndex = 1:numel(hardwareTicksNs)
    swept = model(100000,120,800,800,4000,1, ...
        hardwareTicksNs(sweepIndex),1);
    hardwareTickSweepOffsetRangeNs(sweepIndex) = ...
        swept.hardwareOffsetPeakToPeakNs;
    hardwareTickSweepMaxAbsOffsetErrorNs(sweepIndex) = ...
        swept.hardwareMaxAbsClockOffsetErrorNs;
    hardwareTickSweepRoundTripRangeNs(sweepIndex) = ...
        swept.hardwareRoundTripPeakToPeakNs;
    hardwareTickSweepMaxAbsRoundTripErrorNs(sweepIndex) = ...
        swept.hardwareMaxAbsRoundTripErrorNs;
    softwareTickSweepOffsetRangeNs(sweepIndex) = ...
        swept.softwareOffsetPeakToPeakNs;
end

figure('Name','P07 hardware-tick sweep offset error', ...
    'Tag',experimentFigureTag);
semilogx(hardwareTicksNs,hardwareTickSweepOffsetRangeNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Offset peak-to-peak'); hold on;
semilogx(hardwareTicksNs,hardwareTickSweepMaxAbsOffsetErrorNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Maximum absolute offset error');
hold off; grid on;
xlabel('Hardware timestamp tick (ns)');
ylabel('Offset error metric (ns)');
title('Sweep 2: coarser capture ticks expose quantization');
legend('Location','best');

figure('Name','P07 hardware-tick sweep round-trip error', ...
    'Tag',experimentFigureTag);
semilogx(hardwareTicksNs,hardwareTickSweepRoundTripRangeNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Round-trip peak-to-peak'); hold on;
semilogx(hardwareTicksNs,hardwareTickSweepMaxAbsRoundTripErrorNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Maximum absolute round-trip error');
hold off; grid on;
xlabel('Hardware timestamp tick (ns)');
ylabel('Round-trip error metric (ns)');
title('Sweep 2 changed view: four quantized stamps combine');
legend('Location','best');

assert(isequal(hardwareTickSweepOffsetRangeNs,[0 4 32]) && ...
    isequal(hardwareTickSweepMaxAbsOffsetErrorNs,[0 2 22]) && ...
    isequal(hardwareTickSweepRoundTripRangeNs,[0 8 64]) && ...
    isequal(hardwareTickSweepMaxAbsRoundTripErrorNs,[0 4 52]), ...
    'Hardware-tick sweep metrics changed.');
assert(isequal(softwareTickSweepOffsetRangeNs,[350 350 350]), ...
    'Hardware tick must not change software-capture estimates.');
disp(['Mechanism: hardware placement removes the modeled host path, but a q ns tick still ' ...
    'rounds each captured time by at most q/2 in this teaching quantizer.']);

%% Deliberately broken case - omit reference-plane calibration
calibrated = model(100000,120,800,800,4000,1,1,1);
broken = model(100000,120,800,800,4000,1,1,0);
fprintf(['Broken calibration: eight identical-looking hardware estimates report %.0f ns ' ...
    'instead of %.0f ns; round trip reports %.0f ns instead of %.0f ns.\n'], ...
    broken.hardwareMeanClockOffsetEstimateNs,broken.clockOffsetNs, ...
    broken.hardwareEstimatedRoundTripDelayNs(1), ...
    broken.trueNetworkRoundTripDelayNs);

figure('Name','P07 broken calibration stable offset bias', ...
    'Tag',experimentFigureTag);
plot(broken.exchangeIndex,calibrated.hardwareEstimatedClockOffsetNs,'o-', ...
    'LineWidth',1.4,'DisplayName','Calibrated reference plane'); hold on;
plot(broken.exchangeIndex,broken.hardwareEstimatedClockOffsetNs,'s-', ...
    'LineWidth',1.4,'DisplayName','Calibration omitted');
yline(broken.clockOffsetNs,'k--','LineWidth',1.2, ...
    'DisplayName','Simulated true offset');
hold off; grid on;
xlabel('Deterministic exchange index');
ylabel('Hardware offset estimate (ns)');
title('Deliberately broken calibration: zero spread, nonzero bias');
legend('Location','best');

figure('Name','P07 broken calibration reference-plane residual', ...
    'Tag',experimentFigureTag);
bar(1:4,[calibrated.hardwareTimestampErrorNs(:,1), ...
    broken.hardwareTimestampErrorNs(:,1)]); grid on;
set(gca,'XTick',1:4,'XTickLabel',eventLabels,'XTickLabelRotation',18);
xlabel('Timestamp event');
ylabel('Timestamp error at modeled reference plane (ns)');
title('Broken-case symptom: pipeline delay remains in captured time');
legend({'Calibrated','Calibration omitted'},'Location','best');

assert(isequal(calibrated.hardwareEstimatedClockOffsetNs,120 * ones(1,8)) && ...
    isequal(calibrated.hardwareEstimatedRoundTripDelayNs,1600 * ones(1,8)), ...
    'Fine-tick calibrated limiting case changed.');
assert(isequal(broken.hardwareEstimatedClockOffsetNs,150 * ones(1,8)) && ...
    isequal(broken.hardwareEstimatedRoundTripDelayNs,1740 * ones(1,8)) && ...
    broken.hardwareOffsetPeakToPeakNs == 0 && ...
    ~broken.hardwareCalibrationMatched && ...
    strcmp(broken.hardwareState,'miscalibrated-reference-plane'), ...
    'Broken calibration must remain stable, precise-looking, and biased.');

%% Read and explain the mechanism
disp('Mechanism: capture placement and calibration determine e_i; precision is only the spread of repeated values, not proof of accuracy.');
disp('Even calibrated fine-tick hardware retains P06 path-asymmetry bias: (forward delay - reverse delay)/2.');
disp('Teach back the error equation, both levers, the broken calibration symptom, and the simulation-only boundary.');
