%% P13 - Budget an End-to-End Deadline
experimentFigureTag = 'P13ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the complete-path budget mechanism
disp(['What inputs, observable effects, and failure modes matter when ' ...
    'you budget an End-to-End Deadline?']);
disp(['P04 exposed queue wait, P11 kept overload visible upstream, and ' ...
    'P12 exposed a 26 ms coordination-evidence wait.']);
disp(['P13 owns each declared contribution exactly once: ' ...
    'R_e2e = sum(c_i). A complete plan also requires sum(b_i) <= D.']);
disp(['Slack decomposes as D - sum(c_i) = ' ...
    '[D - sum(b_i)] + sum(b_i - c_i).']);
disp(['Predict whether a queue stage can exceed its allocation while the ' ...
    'complete path still remains inside the end-to-end deadline.']);

%% Visualize the deterministic baseline stage view
baseline = model(12,26,90,true);
fprintf(['Baseline: complete path %.0f ms, assigned budget %.0f ms, ' ...
    'deadline %.0f ms, end-to-end slack %.0f ms, allocation reserve %.0f ms.\n'], ...
    baseline.fullPathContributionMs,baseline.assignedBudgetTotalMs, ...
    baseline.deadlineMs,baseline.deadlineSlackMs, ...
    baseline.allocationReserveMs);

figure('Name','P13 baseline stage contributions and allocations', ...
    'Tag',experimentFigureTag);
bar(baseline.stageId,[baseline.stageContributionMs(:) ...
    baseline.assignedStageBudgetMs(:)]);
grid on;
xlabel('Ordered end-to-end stage (identifier)');
ylabel('Declared contribution or allocation (ms)');
title('Baseline view 1: every causal stage has one owned allocation');
set(gca,'XTick',baseline.stageId,'XTickLabel', ...
    {'Source','Queue','Network','Coordination','Destination'});
legend({'Declared contribution','Assigned stage budget'}, ...
    'Location','best');

assert(isequal(baseline.stageContributionMs,[8 12 10 26 9]) && ...
    isequal(baseline.referenceStageBudgetMs,[10 16 14 32 12]) && ...
    isequal(baseline.stageBudgetMarginMs,[2 4 4 6 3]), ...
    'Baseline stage contributions or allocations changed.');
assert(baseline.fullPathContributionMs == 65 && ...
    baseline.assignedBudgetTotalMs == 84 && ...
    baseline.deadlineSlackMs == 25 && ...
    baseline.allocationReserveMs == 6 && ...
    baseline.stageMarginTotalMs == 19, ...
    'Baseline deadline arithmetic changed.');

%% Change the view to cumulative contribution, allocation, and deadline
figure('Name','P13 baseline cumulative end-to-end budget', ...
    'Tag',experimentFigureTag);
plot(0:baseline.stageCount,baseline.cumulativeFullPathMs,'o-', ...
    'LineWidth',1.5,'DisplayName','Complete path contribution');
hold on;
plot(0:baseline.stageCount,baseline.cumulativeAssignedBudgetMs,'s-', ...
    'LineWidth',1.5,'DisplayName','Assigned cumulative budget');
yline(baseline.deadlineMs,'k--','LineWidth',1.2, ...
    'DisplayName','End-to-end deadline');
hold off;
grid on;
xlabel('Completed stage boundary (count)');
ylabel('Cumulative time (ms)');
title('Baseline view 2: stage margin plus reserve equals path slack');
legend('Location','best');

assert(isequal(baseline.cumulativeFullPathMs,[0 8 20 30 56 65]) && ...
    isequal(baseline.cumulativeAssignedBudgetMs,[0 10 26 40 72 84]) && ...
    baseline.budgetCoverageComplete && ...
    baseline.allStageBudgetsMet && ...
    baseline.allocationFitsDeadline && ...
    baseline.endToEndBoundMeetsDeadline && ...
    baseline.budgetPlanCredible && ...
    baseline.fullSlackIdentityResidualMs == 0, ...
    'Baseline cumulative budget identity changed.');

%% Sweep 1: change only queue/admission wait
queueWaitValuesMs = [0 6 12 24];
queueSweepFullPathMs = zeros(size(queueWaitValuesMs));
queueSweepDeadlineSlackMs = zeros(size(queueWaitValuesMs));
queueSweepStageMarginMs = zeros(size(queueWaitValuesMs));
queueSweepAllStageBudgetsMet = false(size(queueWaitValuesMs));
for caseIndex = 1:numel(queueWaitValuesMs)
    current = model(queueWaitValuesMs(caseIndex),26,90,true);
    queueSweepFullPathMs(caseIndex) = current.fullPathContributionMs;
    queueSweepDeadlineSlackMs(caseIndex) = current.deadlineSlackMs;
    queueSweepStageMarginMs(caseIndex) = ...
        current.stageBudgetMarginMs(2);
    queueSweepAllStageBudgetsMet(caseIndex) = ...
        current.allStageBudgetsMet;
end

figure('Name','P13 sweep 1 queue wait', ...
    'Tag',experimentFigureTag);
subplot(3,1,1);
plot(queueWaitValuesMs,queueSweepFullPathMs,'o-', ...
    'LineWidth',1.5);
grid on;
xlabel('Queue/admission wait (ms)');
ylabel('Complete path contribution (ms)');
title('Sweep 1: queue wait adds one-for-one to the complete path');
subplot(3,1,2);
plot(queueWaitValuesMs,queueSweepDeadlineSlackMs,'s-', ...
    'LineWidth',1.5);
grid on;
xlabel('Queue/admission wait (ms)');
ylabel('End-to-end deadline slack (ms)');
title('The fixed 90 ms deadline loses the same amount of slack');
subplot(3,1,3);
plot(queueWaitValuesMs,queueSweepStageMarginMs,'d-', ...
    'LineWidth',1.5);
hold on;
yline(0,'k--','LineWidth',1.2);
hold off;
grid on;
xlabel('Queue/admission wait (ms)');
ylabel('Queue-stage allocation margin (ms)');
title('A local allocation can fail before the end-to-end deadline');

assert(isequal(queueSweepFullPathMs,[53 59 65 77]) && ...
    isequal(queueSweepDeadlineSlackMs,[37 31 25 13]) && ...
    isequal(queueSweepStageMarginMs,[16 10 4 -8]) && ...
    isequal(queueSweepAllStageBudgetsMet,[true true true false]), ...
    'Queue-wait sweep changed unexpectedly.');

%% Reset, then sweep 2: change only the end-to-end deadline
deadlineValuesMs = [60 65 84 90];
deadlineSweepFullPathMs = zeros(size(deadlineValuesMs));
deadlineSweepSlackMs = zeros(size(deadlineValuesMs));
deadlineSweepAllocationReserveMs = zeros(size(deadlineValuesMs));
deadlineSweepPathMet = false(size(deadlineValuesMs));
deadlineSweepAllocationFits = false(size(deadlineValuesMs));
for caseIndex = 1:numel(deadlineValuesMs)
    current = model(12,26,deadlineValuesMs(caseIndex),true);
    deadlineSweepFullPathMs(caseIndex) = ...
        current.fullPathContributionMs;
    deadlineSweepSlackMs(caseIndex) = current.deadlineSlackMs;
    deadlineSweepAllocationReserveMs(caseIndex) = ...
        current.allocationReserveMs;
    deadlineSweepPathMet(caseIndex) = ...
        current.endToEndBoundMeetsDeadline;
    deadlineSweepAllocationFits(caseIndex) = ...
        current.allocationFitsDeadline;
end

figure('Name','P13 sweep 2 end-to-end deadline', ...
    'Tag',experimentFigureTag);
subplot(3,1,1);
plot(deadlineValuesMs,deadlineSweepFullPathMs,'o-', ...
    'LineWidth',1.5);
grid on;
xlabel('End-to-end deadline (ms)');
ylabel('Complete path contribution (ms)');
title('Sweep 2: changing a requirement does not make a stage faster');
subplot(3,1,2);
plot(deadlineValuesMs,deadlineSweepSlackMs,'s-', ...
    'LineWidth',1.5);
hold on;
yline(0,'k--','LineWidth',1.2);
hold off;
grid on;
xlabel('End-to-end deadline (ms)');
ylabel('End-to-end deadline slack (ms)');
title('Exact complete-path equality passes the deadline boundary');
subplot(3,1,3);
plot(deadlineValuesMs,deadlineSweepAllocationReserveMs,'d-', ...
    'LineWidth',1.5);
hold on;
yline(0,'k--','LineWidth',1.2);
hold off;
grid on;
xlabel('End-to-end deadline (ms)');
ylabel('Unassigned allocation reserve (ms)');
title('The complete allocation plan fits only at 84 ms or later');

assert(isequal(deadlineSweepFullPathMs,[65 65 65 65]) && ...
    isequal(deadlineSweepSlackMs,[-5 0 19 25]) && ...
    isequal(deadlineSweepAllocationReserveMs,[-24 -19 0 6]) && ...
    isequal(deadlineSweepPathMet,[false true true true]) && ...
    isequal(deadlineSweepAllocationFits,[false false true true]), ...
    'Deadline sweep changed unexpectedly.');

%% Read the mechanism before the deliberately broken case
disp(['Queue wait and coordination evidence are different causal stages. ' ...
    'Both must appear exactly once in the complete path.']);
disp(['A positive total slack can absorb a local allocation overrun, but ' ...
    'only a complete ownership map makes that trade visible and reviewable.']);

%% Deliberately broken case: omit coordination from budget ownership
% Broken assumption: a deadline budget is credible even if one causal stage is omitted.
broken = model(12,26,60,false);
completeTight = model(12,26,60,true);
figure('Name','P13 deliberately broken incomplete budget', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
bar([broken.accountedPathContributionMs ...
    broken.fullPathContributionMs broken.deadlineMs]);
grid on;
set(gca,'XTickLabel', ...
    {'Incomplete accounted path','Complete path','Deadline'});
ylabel('Time (ms)');
title('Broken case: omitted coordination manufactures apparent slack');
subplot(2,1,2);
bar(broken.stageId,[broken.budgetedStageMask(:) ...
    ones(broken.stageCount,1)]);
grid on;
set(gca,'XTick',broken.stageId,'XTickLabel', ...
    {'Source','Queue','Network','Coordination','Destination'});
xlabel('Ordered end-to-end stage (identifier)');
ylabel('Stage represented (0 or 1)');
title('The complete path retains a 26 ms stage that the plan does not own');
legend({'Budget ownership','Complete path'},'Location','best');

assert(broken.accountedPathContributionMs == 39 && ...
    broken.apparentAccountedSlackMs == 21 && ...
    broken.unbudgetedContributionMs == 26 && ...
    broken.fullPathContributionMs == 65 && ...
    broken.deadlineSlackMs == -5 && ...
    ~broken.budgetCoverageComplete && ...
    broken.accountedPathFitsDeadline && ...
    ~broken.endToEndBoundMeetsDeadline && ...
    broken.falseConfidenceSymptom && ...
    ~completeTight.falseConfidenceSymptom, ...
    'Broken incomplete-budget symptom changed.');
disp(['Broken assumption: a deadline budget is credible even if one causal ' ...
    'stage is omitted. The apparent +21 ms hides a complete-path -5 ms miss.']);

%% Classify deadline, timeout, cancellation, rollback, and recovery
exactDeadline = model(12,26,65,true);
justBeforeDeadline = model(12,26,65 - 1e-12,true);
localAllocationBreach = model(24,26,90,true);
recoveryTarget = model(12,26,90,true);

assert(exactDeadline.endToEndBoundMeetsDeadline && ...
    exactDeadline.deadlineSlackMs == 0 && ...
    exactDeadline.deadlineTiePasses);
assert(~justBeforeDeadline.endToEndBoundMeetsDeadline && ...
    justBeforeDeadline.deadlineSlackMs < 0);
assert(localAllocationBreach.endToEndBoundMeetsDeadline && ...
    ~localAllocationBreach.allStageBudgetsMet && ...
    localAllocationBreach.stageAllocationExceededWhileDeadlineMet);
assert(recoveryTarget.deadlineOnlyClassifies && ...
    ~recoveryTarget.timeoutModeled && ...
    ~recoveryTarget.actualWallClockWaitPerformed && ...
    ~recoveryTarget.cancellationModeled && ...
    ~recoveryTarget.actualAsynchronousCancellationPerformed && ...
    ~recoveryTarget.rollbackModeled && ...
    ~recoveryTarget.actualRollbackPerformed && ...
    ~recoveryTarget.recoveryModeled && ...
    recoveryTarget.freshEvaluationRequiredForRecoveryTarget && ...
    isequaln(recoveryTarget,baseline));
disp(['The deadline classifies one declared bound; it starts no timeout and ' ...
    'does not cancel, roll back, or accelerate work.']);
disp(['Restoring inputs in a fresh call reproduces a recovery target only. ' ...
    'No live retry, replay, or recovery mechanism ran.']);

