%% P08 - Distribute a Time-Triggered Schedule
experimentFigureTag = 'P08ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the shared-time and version-coherence mechanism
disp('What inputs, observable effects, and failure modes matter when you distribute a Time-Triggered Schedule?');
disp(['P07 bounded where a timestamp lands. P08 uses residual clock error to ask when ' ...
    'four nodes actually execute a shared schedule and whether they execute the same version.']);
disp(['Mechanism: with node clock C_i(t)=t+e_i, local action time A+s_i fires at ' ...
    'true time A+s_i-e_i. A coherent schedule keeps at least guard-2E in the worst case.']);
disp('Every action occupies the same exclusive, non-preemptive shared channel.');

%% Visualize the deterministic baseline action windows
baseline = model(20,1500,1,true);
relativeStartUs = baseline.actionStartRelativeToActivationUs;
relativeEndUs = baseline.actionEndTrueTimeUs - baseline.activationLeadUs;
fprintf(['Baseline: all %d nodes staged version 2; residual clock offsets span %.0f us. ' ...
    'Minimum true separation is %.0f us and the analytical lower bound is %.0f us.\n'], ...
    baseline.readyNodeCount,baseline.maximumPairwiseClockOffsetUs, ...
    baseline.minimumSeparationUs,baseline.coherentGuaranteedMinSeparationUs);

figure('Name','P08 baseline true action windows', ...
    'Tag',experimentFigureTag);
hold on;
for nodeIndex = 1:baseline.nodeCount
    plot([relativeStartUs(nodeIndex),relativeEndUs(nodeIndex)], ...
        [nodeIndex,nodeIndex],'-','LineWidth',8, ...
        'DisplayName',baseline.nodeLabels{nodeIndex});
    plot(baseline.versionTwoPhaseUs(nodeIndex),nodeIndex,'kx', ...
        'LineWidth',1.5,'HandleVisibility','off');
end
hold off; grid on;
xlabel('True time relative to shared activation epoch (us)');
ylabel('Scheduled node');
title('Baseline view 1: true occupancy of one exclusive shared channel');
set(gca,'YTick',baseline.nodeIndex,'YTickLabel',baseline.nodeLabels);
legend('Location','best');

assert(isequal(baseline.clockOffsetUs,[-20 10 20 -10]) && ...
    isequal(relativeStartUs,[20 240 480 760]) && ...
    isequal(relativeEndUs,[180 400 640 920]) && ...
    isequal(baseline.separationToNextActionUs,[60 80 120 100]) && ...
    baseline.minimumSeparationUs == 60 && ...
    baseline.collisionCount == 0, ...
    'Baseline true action windows or cyclic separations changed.');

%% Change the view to distribution readiness at the common epoch
figure('Name','P08 baseline schedule readiness', ...
    'Tag',experimentFigureTag);
bar(baseline.nodeIndex,[baseline.scheduleReadyLocalTimeUs(:), ...
    baseline.activationLeadUs * ones(baseline.nodeCount,1)]); grid on;
xlabel('Scheduled node');
ylabel('Node-local time after publication (us)');
title('Baseline view 2: every staged schedule precedes common activation');
set(gca,'XTick',baseline.nodeIndex,'XTickLabel',baseline.nodeLabels);
legend({'Schedule ready','Shared activation A'},'Location','best');

assert(isequal(baseline.scheduleReadyTrueTimeUs,[260 500 880 1220]) && ...
    isequal(baseline.scheduleReadyLocalTimeUs,[240 510 900 1210]) && ...
    isequal(baseline.activationSlackUs,[1260 990 600 290]) && ...
    baseline.allNodesReady && baseline.newVersionSelectedForAllNodes && ...
    isequal(baseline.activeScheduleVersion,[2 2 2 2]) && ...
    strcmp(baseline.scheduleState,'new-schedule-selected'), ...
    'Baseline readiness or coherent activation state changed.');

%% Sweep 1 - change only the residual clock-error bound
clockErrorBoundsUs = [0 20 40];
clockSweepMinimumSeparationUs = zeros(size(clockErrorBoundsUs));
clockSweepGuaranteedSeparationUs = zeros(size(clockErrorBoundsUs));
clockSweepMaximumStartErrorUs = zeros(size(clockErrorBoundsUs));
clockSweepPairwiseOffsetUs = zeros(size(clockErrorBoundsUs));
for sweepIndex = 1:numel(clockErrorBoundsUs)
    swept = model(clockErrorBoundsUs(sweepIndex),1500,1,true);
    clockSweepMinimumSeparationUs(sweepIndex) = ...
        swept.minimumSeparationUs;
    clockSweepGuaranteedSeparationUs(sweepIndex) = ...
        swept.coherentGuaranteedMinSeparationUs;
    clockSweepMaximumStartErrorUs(sweepIndex) = ...
        max(abs(swept.actionStartErrorUs));
    clockSweepPairwiseOffsetUs(sweepIndex) = ...
        swept.maximumPairwiseClockOffsetUs;
end

figure('Name','P08 clock-error sweep guard margin', ...
    'Tag',experimentFigureTag);
plot(clockErrorBoundsUs,clockSweepMinimumSeparationUs,'o-', ...
    'LineWidth',1.4,'DisplayName','Actual fixture minimum'); hold on;
plot(clockErrorBoundsUs,clockSweepGuaranteedSeparationUs,'s--', ...
    'LineWidth',1.4,'DisplayName','Guard - 2E lower bound');
hold off; grid on;
xlabel('Residual clock-error bound E (us)');
ylabel('Minimum cyclic action separation (us)');
title('Sweep 1: clock uncertainty consumes reserved guard time');
legend('Location','best');

figure('Name','P08 clock-error sweep start displacement', ...
    'Tag',experimentFigureTag);
plot(clockErrorBoundsUs,clockSweepMaximumStartErrorUs,'o-', ...
    'LineWidth',1.4,'DisplayName','Maximum action start error'); hold on;
plot(clockErrorBoundsUs,clockSweepPairwiseOffsetUs,'s-', ...
    'LineWidth',1.4,'DisplayName','Pairwise clock-offset span');
hold off; grid on;
xlabel('Residual clock-error bound E (us)');
ylabel('Timing error metric (us)');
title('Sweep 1 changed view: local offset becomes true-time displacement');
legend('Location','best');

assert(isequal(clockSweepMinimumSeparationUs,[90 60 30]) && ...
    isequal(clockSweepGuaranteedSeparationUs,[90 50 10]) && ...
    isequal(clockSweepMaximumStartErrorUs,[0 20 40]) && ...
    isequal(clockSweepPairwiseOffsetUs,[0 40 80]), ...
    'Clock-error sweep metrics changed.');
disp(['Mechanism: any pair of node offsets can differ by at most 2E, so a coherent ' ...
    '90 us nominal guard has the conservative lower bound 90-2E.']);

%% Sweep 2 - reset clock error and change only activation lead time
activationLeadsUs = [600 1000 1500];
leadSweepReadyNodeCount = zeros(size(activationLeadsUs));
leadSweepMinimumSlackUs = zeros(size(activationLeadsUs));
leadSweepSelectionWithheld = false(size(activationLeadsUs));
leadSweepNewVersionSelected = false(size(activationLeadsUs));
leadSweepMinimumSeparationUs = zeros(size(activationLeadsUs));
for sweepIndex = 1:numel(activationLeadsUs)
    swept = model(20,activationLeadsUs(sweepIndex),1,true);
    leadSweepReadyNodeCount(sweepIndex) = swept.readyNodeCount;
    leadSweepMinimumSlackUs(sweepIndex) = swept.minimumActivationSlackUs;
    leadSweepSelectionWithheld(sweepIndex) = ...
        swept.newVersionSelectionWithheld;
    leadSweepNewVersionSelected(sweepIndex) = ...
        swept.newVersionSelectedForAllNodes;
    leadSweepMinimumSeparationUs(sweepIndex) = ...
        swept.minimumSeparationUs;
end

figure('Name','P08 activation-lead sweep readiness', ...
    'Tag',experimentFigureTag);
stairs(activationLeadsUs,leadSweepReadyNodeCount,'o-', ...
    'LineWidth',1.4); grid on;
xlabel('Shared activation lead after publication (us)');
ylabel('Nodes ready before activation (count)');
title('Sweep 2: distribution and validation need staging time');
ylim([0 baseline.nodeCount + 0.5]);

figure('Name','P08 activation-lead sweep slack', ...
    'Tag',experimentFigureTag);
plot(activationLeadsUs,leadSweepMinimumSlackUs,'o-', ...
    'LineWidth',1.4,'DisplayName','Minimum node readiness slack'); hold on;
yline(0,'k--','DisplayName','Ready exactly at activation');
hold off; grid on;
xlabel('Shared activation lead after publication (us)');
ylabel('Minimum readiness slack (us)');
title('Sweep 2 changed view: negative slack withholds the new version');
legend('Location','best');

assert(isequal(leadSweepReadyNodeCount,[2 3 4]) && ...
    isequal(leadSweepMinimumSlackUs,[-610 -210 290]) && ...
    isequal(leadSweepSelectionWithheld,[true true false]) && ...
    isequal(leadSweepNewVersionSelected,[false false true]) && ...
    isequal(leadSweepMinimumSeparationUs,[60 60 60]), ...
    'Activation-lead sweep readiness, selection, or timing changed.');
disp(['Mechanism: a future activation epoch does not accelerate distribution. The ' ...
    'version-coherent policy retains the old version until every node is staged.']);

%% Deliberately broken case - allow a partial schedule-version activation
coherentRetainOld = model(20,1000,1,true);
broken = model(20,1000,1,false);
fprintf(['Broken partial activation: %d nodes switch to version 2 while %d node retains ' ...
    'version 1; Node C and Node D overlap for %.0f us.\n'], ...
    sum(broken.activeScheduleVersion == 2), ...
    sum(broken.activeScheduleVersion == 1),broken.maximumOverlapUs);

figure('Name','P08 broken mixed schedule versions', ...
    'Tag',experimentFigureTag);
bar(broken.nodeIndex,[coherentRetainOld.activeScheduleVersion(:), ...
    broken.activeScheduleVersion(:)]); grid on;
xlabel('Scheduled node');
ylabel('Active schedule version (integer)');
title('Deliberately broken case: ready nodes switch independently');
set(gca,'XTick',broken.nodeIndex,'XTickLabel',broken.nodeLabels);
legend({'All-or-nothing policy','Partial activation'},'Location','best');
ylim([0 2.5]);

figure('Name','P08 broken cyclic action separation', ...
    'Tag',experimentFigureTag);
bar(1:broken.actionCount,[coherentRetainOld.separationToNextActionUs(:), ...
    broken.separationToNextActionUs(:)]); grid on;
xlabel('Action transition in true-time order (including cycle wrap)');
ylabel('Separation before next action (us)');
title('Broken-case symptom: a negative separation is an overlap');
legend({'Coherent retain-old','Mixed versions'},'Location','best');

assert(isequal(coherentRetainOld.activeScheduleVersion,[1 1 1 1]) && ...
    coherentRetainOld.newVersionSelectionWithheld && ...
    coherentRetainOld.oldVersionRetainedForAllNodes && ...
    coherentRetainOld.configurationCoherent && ...
    coherentRetainOld.collisionCount == 0 && ...
    isequal(coherentRetainOld.separationToNextActionUs,[60 110 60 130]), ...
    'All-or-nothing retain-old behavior changed.');
assert(isequal(broken.activeScheduleVersion,[2 2 2 1]) && ...
    isequal(broken.selectedPhaseUs,[0 250 500 500]) && ...
    isequal(broken.separationToNextActionUs,[60 80 -130 350]) && ...
    isequal(broken.collisionFromNodeIndex,3) && ...
    isequal(broken.collisionToNodeIndex,4) && ...
    broken.maximumOverlapUs == 130 && broken.collisionCount == 1 && ...
    ~broken.configurationCoherent && ...
    strcmp(broken.scheduleState,'mixed-version-overlap'), ...
    'Broken mixed-version overlap fixture changed.');

%% Read and explain the mechanism
disp(['Mechanism: synchronized clocks make a shared timestamp meaningful, guard absorbs ' ...
    'bounded relative clock error on one exclusive channel, and staged all-or-nothing ' ...
    'selection preserves one slot map.']);
disp(['Retaining the old map withholds a new selection; it is not an implemented ' ...
    'rollback, acknowledgment, commit, timeout, or consensus protocol.']);
disp('Teach back clock-error guard consumption, activation readiness, mixed-version overlap, and the simulation-only boundary.');
