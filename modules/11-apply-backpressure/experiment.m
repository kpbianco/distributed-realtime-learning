%% P11 - Apply Backpressure
experimentFigureTag = 'P11ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the completion-credit backpressure mechanism
disp('What inputs, observable effects, and failure modes matter when you apply Backpressure?');
disp(['P10 bounded receiver storage. P11 lets one ordered producer observe ' ...
    'whether that receiver has an available slot.']);
disp(['Demand ready R_i, admission A_i, service start S_i, and completion D_i ' ...
    'separate offered work from admitted and completed work.']);
disp(['A completion returns one credit before a coincident admission. ' ...
    'Backpressure moves excess demand upstream; it does not accelerate service.']);
disp('Predict where overload becomes visible if receiver occupancy cannot exceed three messages.');

%% Visualize the deterministic baseline lifecycle view
baseline = model(10,20,3,200,true,false);
fprintf(['Baseline: %d/%d complete at %.0f ms; receiver high-water %d messages; ' ...
    'upstream wait %.0f message-ms (max %.0f ms).\n'], ...
    baseline.completedCount,baseline.messageCount, ...
    baseline.completionTimeOfBatchMs,baseline.receiverHighWaterMessages, ...
    baseline.totalUpstreamWaitMessageMs,baseline.maxUpstreamWaitMs);

figure('Name','P11 baseline demand, admission, and completion', ...
    'Tag',experimentFigureTag);
plot(baseline.messageId,baseline.demandReadyTimeMs,'o-', ...
    baseline.messageId,baseline.admissionTimeMs,'s--', ...
    baseline.messageId,baseline.completionTimeMs,'d-', ...
    'LineWidth',1.5);
grid on;
xlabel('Ordered message identifier (integer)');
ylabel('Time from first demand (ms)');
title('Baseline view 1: finite readiness delays admission, not demand');
legend({'Demand ready','Receiver admission','Consumer completion'}, ...
    'Location','best');

assert(isequal(baseline.demandReadyTimeMs,0:10:110) && ...
    isequal(baseline.admissionTimeMs, ...
    [0 10 20 30 40 60 80 100 120 140 160 180]) && ...
    isequal(baseline.completionTimeMs,20:20:240), ...
    'Baseline lifecycle times changed.');
assert(baseline.losslessCompletion && ...
    baseline.receiverCapacityRespected && ...
    baseline.acceptedPrefixPreserved && ...
    isequal(baseline.admittedMessageIds,1:12), ...
    'Baseline flow contract changed.');

%% Change the view to receiver occupancy and upstream pending demand
figure('Name','P11 baseline pressure location', ...
    'Tag',experimentFigureTag);
stairs(baseline.observationTimeMs, ...
    baseline.receiverOccupancyMessages,'o-','LineWidth',1.5);
hold on;
stairs(baseline.observationTimeMs, ...
    baseline.upstreamPendingMessages,'s--','LineWidth',1.5);
hold off;
grid on;
xlabel('Analytical event time (ms)');
ylabel('Messages (count)');
title('Baseline view 2: receiver stays bounded while pressure moves upstream');
legend({'Receiver unfinished','Upstream pending'},'Location','best');

assert(isequal(baseline.upstreamWaitUntilDecisionMs, ...
    [0 0 0 0 0 10 20 30 40 50 60 70]) && ...
    baseline.totalUpstreamWaitMessageMs == 280 && ...
    baseline.maxUpstreamWaitMs == 70 && ...
    baseline.receiverHighWaterMessages == 3 && ...
    baseline.peakUpstreamPendingMessages == 4, ...
    'Baseline pressure-location metrics changed.');
assert(isequal(baseline.receiverQueueWaitMs, ...
    [0 10 20 30 40 40 40 40 40 40 40 40]), ...
    'Baseline receiver FIFO wait changed.');

%% Sweep 1: change only the producer interval
producerIntervalsMs = [5 10 20 30];
intervalSweepTotalUpstreamWait = zeros(size(producerIntervalsMs));
intervalSweepMaxUpstreamWait = zeros(size(producerIntervalsMs));
intervalSweepReceiverHighWater = zeros(size(producerIntervalsMs));
intervalSweepCompletionTimeMs = zeros(size(producerIntervalsMs));
intervalSweepCompletedCount = zeros(size(producerIntervalsMs));
for caseIndex = 1:numel(producerIntervalsMs)
    current = model(producerIntervalsMs(caseIndex),20,3,200,true,false);
    intervalSweepTotalUpstreamWait(caseIndex) = ...
        current.totalUpstreamWaitMessageMs;
    intervalSweepMaxUpstreamWait(caseIndex) = ...
        current.maxUpstreamWaitMs;
    intervalSweepReceiverHighWater(caseIndex) = ...
        current.receiverHighWaterMessages;
    intervalSweepCompletionTimeMs(caseIndex) = ...
        current.completionTimeOfBatchMs;
    intervalSweepCompletedCount(caseIndex) = current.completedCount;
end

figure('Name','P11 sweep 1 producer interval', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
plot(producerIntervalsMs,intervalSweepTotalUpstreamWait,'o-', ...
    producerIntervalsMs,intervalSweepMaxUpstreamWait,'s--', ...
    'LineWidth',1.5);
grid on;
xlabel('Producer demand interval (ms)');
ylabel('Upstream wait (message-ms or ms)');
title('Sweep 1: faster offered demand accumulates upstream pressure');
legend({'Total wait (message-ms)','Maximum wait (ms)'}, ...
    'Location','best');
subplot(2,1,2);
plot(producerIntervalsMs,intervalSweepReceiverHighWater,'d-', ...
    producerIntervalsMs,intervalSweepCompletionTimeMs,'^-', ...
    'LineWidth',1.5);
grid on;
xlabel('Producer demand interval (ms)');
ylabel('High-water (messages) or completion (ms)');
title('Readiness bounds occupancy but cannot make the consumer faster');
legend({'Receiver high-water (messages)','Batch completion (ms)'}, ...
    'Location','best');

assert(isequal(intervalSweepTotalUpstreamWait,[585 280 0 0]) && ...
    isequal(intervalSweepMaxUpstreamWait,[125 70 0 0]) && ...
    isequal(intervalSweepReceiverHighWater,[3 3 1 1]) && ...
    isequal(intervalSweepCompletionTimeMs,[240 240 240 350]) && ...
    isequal(intervalSweepCompletedCount,[12 12 12 12]), ...
    'Producer-interval sweep changed unexpectedly.');

%% Reset, then sweep 2: change only receiver capacity
receiverCapacities = [1 2 3 6];
capacitySweepTotalUpstreamWait = zeros(size(receiverCapacities));
capacitySweepMaxUpstreamWait = zeros(size(receiverCapacities));
capacitySweepMaxReceiverWait = zeros(size(receiverCapacities));
capacitySweepCompletionTimeMs = zeros(size(receiverCapacities));
capacitySweepHighWater = zeros(size(receiverCapacities));
for caseIndex = 1:numel(receiverCapacities)
    current = model(10,20,receiverCapacities(caseIndex), ...
        200,true,false);
    capacitySweepTotalUpstreamWait(caseIndex) = ...
        current.totalUpstreamWaitMessageMs;
    capacitySweepMaxUpstreamWait(caseIndex) = ...
        current.maxUpstreamWaitMs;
    capacitySweepMaxReceiverWait(caseIndex) = ...
        current.maxReceiverQueueWaitMs;
    capacitySweepCompletionTimeMs(caseIndex) = ...
        current.completionTimeOfBatchMs;
    capacitySweepHighWater(caseIndex) = ...
        current.receiverHighWaterMessages;
end

figure('Name','P11 sweep 2 receiver capacity', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
bar(receiverCapacities,[capacitySweepTotalUpstreamWait(:), ...
    capacitySweepMaxReceiverWait(:)]);
grid on;
xlabel('Receiver capacity including service (messages)');
ylabel('Wait (message-ms total or ms maximum)');
title('Sweep 2: storage moves waiting from producer to receiver');
legend({'Total upstream wait (message-ms)', ...
    'Maximum receiver queue wait (ms)'},'Location','best');
subplot(2,1,2);
plot(receiverCapacities,capacitySweepHighWater,'o-', ...
    receiverCapacities,capacitySweepCompletionTimeMs,'s--', ...
    'LineWidth',1.5);
grid on;
xlabel('Receiver capacity including service (messages)');
ylabel('High-water (messages) or completion (ms)');
title('More storage changes wait location, not fixed service throughput');
legend({'Receiver high-water (messages)','Batch completion (ms)'}, ...
    'Location','best');

assert(isequal(capacitySweepTotalUpstreamWait,[660 450 280 10]) && ...
    isequal(capacitySweepMaxUpstreamWait,[110 90 70 10]) && ...
    isequal(capacitySweepMaxReceiverWait,[0 20 40 100]) && ...
    isequal(capacitySweepCompletionTimeMs,[240 240 240 240]) && ...
    isequal(capacitySweepHighWater,[1 2 3 6]), ...
    'Receiver-capacity sweep changed unexpectedly.');

%% Read the mechanism before the deliberately broken case
disp(['Completion credit communicates capacity; it is not extra service. ' ...
    'A larger buffer moves wait downstream but leaves completion cadence unchanged.']);
disp(['Pending upstream work remains real work. Removing its wait by ignoring ' ...
    'readiness must produce an explicit reject, drop, or other failure policy.']);

%% Deliberately broken case: ignore receiver readiness
broken = model(10,20,3,200,false,false);
figure('Name','P11 deliberately broken readiness assumption', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
stairs(broken.observationTimeMs,broken.offeredCumulative,'o-', ...
    'LineWidth',1.5);
hold on;
stairs(broken.observationTimeMs,broken.admittedCumulative,'s--', ...
    'LineWidth',1.5);
stairs(broken.observationTimeMs,broken.completedCumulative,'d-', ...
    'LineWidth',1.5);
stairs(broken.observationTimeMs,broken.failedCumulative,'x-', ...
    'LineWidth',1.5);
hold off;
grid on;
xlabel('Analytical event time (ms)');
ylabel('Cumulative messages (count)');
title('Broken case: offered demand separates into completion and loss');
legend({'Demand ready','Admitted','Completed','Dropped'}, ...
    'Location','best');
subplot(2,1,2);
bar([baseline.completedCount baseline.failedCount; ...
    broken.completedCount broken.failedCount]);
grid on;
set(gca,'XTickLabel',{'Backpressure','Readiness ignored'});
ylabel('Messages (count)');
title('Zero upstream wait is not lossless when readiness is ignored');
legend({'Completed','Failed'},'Location','best');

assert(isequal(broken.admittedMessageIds,[1 2 3 4 5 7 9 11]) && ...
    isequal(find(broken.droppedMask),[6 8 10 12]) && ...
    broken.admittedCount == 8 && broken.completedCount == 8 && ...
    broken.droppedCount == 4 && broken.failedCount == 4 && ...
    broken.totalUpstreamWaitMessageMs == 0 && ...
    broken.receiverHighWaterMessages == 3 && ...
    ~broken.acceptedPrefixPreserved && ...
    strcmp(broken.outcome,'readiness-ignored-with-drops'), ...
    'Broken readiness-policy symptom changed.');
disp(['Broken assumption: a producer can ignore receiver readiness without loss. ' ...
    'Messages 6, 8, 10, and 12 disappear at the full receiver.']);

%% Classify timeout, cancellation, rollback, and recovery
exactWaitBoundary = model(10,20,3,10,true,false);
justBeforeWaitBoundary = model(10,20,3,10 - 1e-12,true,false);
zeroCapacity = model(10,20,0,20,true,false);
canceledPending = model(10,20,3,200,true,true);
recoveryTarget = model(10,20,3,200,true,false);
assert(isequal(exactWaitBoundary.admittedMessageIds,1:6) && ...
    exactWaitBoundary.admissionTimeMs(6) == 60 && ...
    exactWaitBoundary.timedOutMask(7) && ...
    all(exactWaitBoundary.suppressedMask(8:12)) && ...
    exactWaitBoundary.acceptedPrefixPreserved);
assert(isequal(justBeforeWaitBoundary.admittedMessageIds,1:5) && ...
    justBeforeWaitBoundary.timedOutMask(6) && ...
    all(justBeforeWaitBoundary.suppressedMask(7:12)) && ...
    justBeforeWaitBoundary.streamStopTimeMs < 60);
assert(zeroCapacity.admittedCount == 0 && ...
    zeroCapacity.timedOutMask(1) && ...
    all(zeroCapacity.suppressedMask(2:12)) && ...
    zeroCapacity.receiverHighWaterMessages == 0);
assert(isequal(canceledPending.admittedMessageIds,1:5) && ...
    canceledPending.canceledMask(6) && ...
    all(canceledPending.suppressedMask(7:12)) && ...
    canceledPending.streamStopTimeMs == 55 && ...
    canceledPending.completionTimeOfBatchMs == 100 && ...
    ~canceledPending.actualAsynchronousCancellationPerformed && ...
    ~canceledPending.rollbackModeled && ...
    canceledPending.acceptedWorkNotRolledBack);
assert(isequal(recoveryTarget.admissionTimeMs,baseline.admissionTimeMs) && ...
    recoveryTarget.losslessCompletion && ...
    ~recoveryTarget.recoveryModeled);
disp(['Readiness wins the exact wait-deadline tie. Timeout or pending ' ...
    'cancellation stops the ordered stream while already admitted work drains.']);
disp(['All waiting and failure decisions are finite arithmetic. No wall-clock ' ...
    'wait, asynchronous cancellation, rollback, retry, or recovery protocol ran.']);

