%% P12 - Build Consensus Intuition
experimentFigureTag = 'P12ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the one-round quorum-evidence mechanism
disp(['What inputs, observable effects, and failure modes matter when ' ...
    'you build Consensus Intuition?']);
disp(['P09 separated replication acknowledgments from universal visibility; ' ...
    'P10 preserved one stream order; P11 exposed finite readiness.']);
disp(['P12 asks when distinct nodes provide enough overlapping evidence for ' ...
    'one value. It does not implement a full consensus protocol.']);
disp(['Vote i is observed at scale*(outbound_i + return_i) + processing_i. ' ...
    'The q-th observed vote completes a certificate.']);
disp('Predict which vote fixes latency when q=3 of five nodes are required.');

%% Visualize the deterministic baseline vote-time view
baseline = model(1,3,100,true,false);
fprintf(['Baseline: value %.0f chosen at %.0f ms by nodes %s; ' ...
    'minimum quorum intersection %d node; %d slower votes not needed.\n'], ...
    baseline.chosenValue,baseline.decisionTimeMs, ...
    mat2str(baseline.decisionCertificateNodeIds), ...
    baseline.minimumQuorumIntersectionNodes, ...
    baseline.unobservedOnlineVoteCount);

figure('Name','P12 baseline vote evidence time', ...
    'Tag',experimentFigureTag);
plot(baseline.nodeId,baseline.potentialVoteTimeMs,'o-', ...
    'LineWidth',1.5,'DisplayName','Potential vote evidence');
hold on;
yline(baseline.decisionTimeMs,'k--','LineWidth',1.2, ...
    'DisplayName','q=3 decision');
hold off;
grid on;
xlabel('Node identifier (integer)');
ylabel('Vote observed by proposer (ms)');
title('Baseline view 1: the third distinct vote fixes decision latency');
legend('Location','best');

assert(isequal(baseline.baseRoundTripDelayMs,[0 12 24 36 60]) && ...
    isequal(baseline.voteProcessingTimeMs,[0 2 2 2 2]) && ...
    isequal(baseline.potentialVoteTimeMs,[0 14 26 38 62]), ...
    'Baseline vote-time decomposition changed.');
assert(baseline.decided && baseline.decisionTimeMs == 26 && ...
    baseline.requestResolutionTimeMs == 26 && ...
    baseline.observedVoteCount == 3 && ...
    isequal(baseline.decisionCertificateNodeIds,1:3) && ...
    baseline.chosenValue == 65, ...
    'Baseline decision contract changed.');

%% Change the view to cumulative evidence and the quorum threshold
figure('Name','P12 baseline cumulative quorum evidence', ...
    'Tag',experimentFigureTag);
stairs(baseline.observationTimeMs, ...
    baseline.observedVoteCumulative,'o-','LineWidth',1.5, ...
    'DisplayName','Distinct votes observed');
hold on;
stairs(baseline.observationTimeMs, ...
    baseline.quorumThresholdTrace,'k--','LineWidth',1.2, ...
    'DisplayName','Quorum threshold q=3');
hold off;
grid on;
xlabel('Analytical event time (ms)');
ylabel('Observed votes (count)');
title('Baseline view 2: decision occurs when evidence reaches q');
legend('Location','best');

assert(isequal(baseline.observationTimeMs,[0 14 26]) && ...
    isequal(baseline.observedVoteCumulative,[1 2 3]) && ...
    baseline.quorumCertificateComplete && ...
    baseline.voteAccountingConserved && ...
    baseline.safeMajorityQuorum && ...
    baseline.minimumQuorumIntersectionNodes == 1 && ...
    baseline.fixedProposerOnlineAssumed && ...
    baseline.unavailableFollowerTolerance == 2 && ...
    ~baseline.hypotheticalConflictingDecisionsPossible, ...
    'Baseline quorum evidence or intersection changed.');

%% Sweep 1: change only round-trip delay scale
delayScales = [0 0.5 1 2];
delaySweepDecisionLatencyMs = zeros(size(delayScales));
delaySweepVoteSpreadMs = zeros(size(delayScales));
delaySweepObservedVotes = zeros(size(delayScales));
for caseIndex = 1:numel(delayScales)
    current = model(delayScales(caseIndex),3,100,true,false);
    delaySweepDecisionLatencyMs(caseIndex) = ...
        current.decisionLatencyMs;
    delaySweepVoteSpreadMs(caseIndex) = current.potentialVoteSpreadMs;
    delaySweepObservedVotes(caseIndex) = current.observedVoteCount;
end

figure('Name','P12 sweep 1 round-trip delay scale', ...
    'Tag',experimentFigureTag);
subplot(3,1,1);
plot(delayScales,delaySweepDecisionLatencyMs,'o-', ...
    'LineWidth',1.5);
grid on;
xlabel('Round-trip delay scale (dimensionless)');
ylabel('Decision latency (ms)');
title('Sweep 1: the q-th vote moves with path delay');
subplot(3,1,2);
plot(delayScales,delaySweepVoteSpreadMs,'s-', ...
    'LineWidth',1.5);
grid on;
xlabel('Round-trip delay scale (dimensionless)');
ylabel('Potential vote-time spread (ms)');
title('Processing remains while scaled path delay changes');
subplot(3,1,3);
plot(delayScales,delaySweepObservedVotes,'d--','LineWidth',1.5);
grid on;
xlabel('Round-trip delay scale (dimensionless)');
ylabel('Votes observed at resolution (count)');
title('Resolution retains only evidence inside its local window');

assert(isequal(delaySweepDecisionLatencyMs,[2 14 26 50]) && ...
    isequal(delaySweepVoteSpreadMs,[2 32 62 122]) && ...
    isequal(delaySweepObservedVotes,[5 3 3 3]), ...
    'Round-trip delay sweep changed unexpectedly.');

%% Reset, then sweep 2: change only quorum size
quorumSizes = [2 3 4 5];
quorumSweepDecisionLatencyMs = zeros(size(quorumSizes));
quorumSweepMinimumIntersection = zeros(size(quorumSizes));
quorumSweepUnavailableFollowerTolerance = zeros(size(quorumSizes));
quorumSweepSafe = false(size(quorumSizes));
for caseIndex = 1:numel(quorumSizes)
    current = model(1,quorumSizes(caseIndex),100,true,false);
    quorumSweepDecisionLatencyMs(caseIndex) = ...
        current.decisionLatencyMs;
    quorumSweepMinimumIntersection(caseIndex) = ...
        current.minimumQuorumIntersectionNodes;
    quorumSweepUnavailableFollowerTolerance(caseIndex) = ...
        current.unavailableFollowerTolerance;
    quorumSweepSafe(caseIndex) = current.safeMajorityQuorum;
end

figure('Name','P12 sweep 2 quorum size', ...
    'Tag',experimentFigureTag);
subplot(3,1,1);
plot(quorumSizes,quorumSweepDecisionLatencyMs,'o-', ...
    'LineWidth',1.5);
grid on;
xlabel('Quorum size (votes)');
ylabel('Decision latency (ms)');
title('Sweep 2: more required evidence adds latency');
subplot(3,1,2);
plot(quorumSizes,quorumSweepMinimumIntersection,'s--', ...
    'LineWidth',1.5);
grid on;
xlabel('Quorum size (votes)');
ylabel('Guaranteed minimum intersection (nodes)');
title('Larger thresholds force greater certificate overlap');
subplot(3,1,3);
bar(quorumSizes,quorumSweepUnavailableFollowerTolerance);
grid on;
xlabel('Quorum size (votes)');
ylabel('Unavailable-follower tolerance (nodes)');
title('Fixed proposer online: larger quorums reduce availability');

assert(isequal(quorumSweepDecisionLatencyMs,[14 26 38 62]) && ...
    isequal(quorumSweepMinimumIntersection,[0 1 3 5]) && ...
    isequal(quorumSweepUnavailableFollowerTolerance,[3 2 1 0]) && ...
    isequal(quorumSweepSafe,[false true true true]), ...
    'Quorum-size sweep changed unexpectedly.');

%% Read the mechanism before the deliberately broken case
disp(['For N=5, two q-sized certificates overlap by at least ' ...
    'max(0,2q-N) nodes. q=3 is the smallest intersecting threshold.']);
disp(['Intersection blocks conflicting certificates only with the named ' ...
    'one-vote-per-node-per-term assumption. Threshold is safety evidence, ' ...
    'not faster propagation or value application.']);

%% Deliberately broken case: use a below-majority quorum
broken = model(1,2,100,true,false);
figure('Name','P12 deliberately broken quorum threshold', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
bar(broken.nodeId,[broken.certificateAMask(:) ...
    broken.certificateBMask(:)]);
grid on;
xlabel('Node identifier (integer)');
ylabel('Certificate membership (0 or 1)');
title('Broken case: q=2 permits disjoint certificates for two values');
legend({'Value X certificate','Value Y certificate'}, ...
    'Location','best');
subplot(2,1,2);
bar([broken.minimumQuorumIntersectionNodes ...
    baseline.minimumQuorumIntersectionNodes]);
grid on;
set(gca,'XTickLabel',{'Broken q=2','Majority q=3'});
ylabel('Guaranteed minimum intersection (nodes)');
title('No intersection means no voter must reject both values');

assert(isequal(broken.certificateANodeIds,[1 2]) && ...
    isequal(broken.certificateBNodeIds,[4 5]) && ...
    isempty(broken.certificateIntersectionNodeIds) && ...
    broken.minimumQuorumIntersectionNodes == 0 && ...
    ~broken.safeMajorityQuorum && ...
    broken.hypotheticalConflictingDecisionsPossible && ...
    ~broken.conflictingCertificatesBlockedByIntersection, ...
    'Broken disjoint-certificate symptom changed.');
disp(['Broken assumption: any fast threshold is enough for agreement. ' ...
    'Two disjoint pairs can certify conflicting values in the same slot.']);

%% Classify timeout, cancellation, rollback, and recovery
exactTimeoutBoundary = model(1,4,38,true,false);
justBeforeTimeoutBoundary = model(1,4,38 - 1e-12,true,false);
unreachableQuorum = model(1,5,100,false,false);
canceledPending = model(1,3,100,true,true);
decisionAtCancellationTie = model(0.75,3,100,true,true);
cancellationTooLate = model(1,2,100,true,true);
cancellationTimeoutTie = model(1,3,20,true,true);
recoveryTarget = model(1,3,100,true,false);

assert(exactTimeoutBoundary.decided && ...
    exactTimeoutBoundary.decisionTimeMs == 38 && ...
    exactTimeoutBoundary.decisionWonTimeoutTie);
assert(justBeforeTimeoutBoundary.timedOut && ...
    justBeforeTimeoutBoundary.observedVoteCount == 3 && ...
    justBeforeTimeoutBoundary.votesStillNeeded == 1 && ...
    justBeforeTimeoutBoundary.potentialQuorumTimeMs == 38 && ...
    ~justBeforeTimeoutBoundary.postResolutionProtocolProgressModeled && ...
    isnan(justBeforeTimeoutBoundary.chosenValue));
assert(unreachableQuorum.timedOut && ...
    ~unreachableQuorum.quorumReachable && ...
    unreachableQuorum.availableVoteCount == 4 && ...
    unreachableQuorum.observedVoteCount == 4 && ...
    unreachableQuorum.votesStillNeeded == 1);
assert(canceledPending.canceled && ...
    canceledPending.requestResolutionTimeMs == 20 && ...
    canceledPending.observedVoteCount == 2 && ...
    canceledPending.votesStillNeeded == 1 && ...
    canceledPending.potentialQuorumTimeMs == 26 && ...
    canceledPending.partialObservedVotesDoNotProveDecision && ...
    canceledPending.cancellationTookEffectOnlyWhilePending && ...
    ~canceledPending.actualAsynchronousCancellationPerformed);
assert(decisionAtCancellationTie.decided && ...
    decisionAtCancellationTie.decisionTimeMs == 20 && ...
    decisionAtCancellationTie.decisionWonCancellationTie && ...
    decisionAtCancellationTie.cancellationCouldNotEraseObservedCertificate);
assert(cancellationTooLate.decided && ...
    cancellationTooLate.decisionTimeMs == 14 && ...
    cancellationTooLate.cancellationCouldNotEraseObservedCertificate);
assert(cancellationTimeoutTie.canceled && ...
    ~cancellationTimeoutTie.timedOut && ...
    cancellationTimeoutTie.requestResolutionTimeMs == 20 && ...
    cancellationTimeoutTie.cancellationHasTimeoutTiePrecedence && ...
    cancellationTimeoutTie.cancellationWonTimeoutTie && ...
    cancellationTimeoutTie.potentialQuorumTimeMs == 26);
assert(~canceledPending.rollbackModeled && ...
    ~canceledPending.actualRollbackPerformed && ...
    canceledPending.observedVotesNotRolledBack && ...
    recoveryTarget.freshEvaluationRequiredForRecoveryTarget && ...
    ~recoveryTarget.recoveryModeled && ...
    isequaln(recoveryTarget,baseline));
disp(['Quorum evidence wins exact timeout and cancellation ties; if only ' ...
    'timeout and cancellation tie, cancellation classifies the result.']);
disp(['Otherwise this evaluator returns without observing a certificate. ' ...
    'Potential later evidence stays visible, but post-resolution protocol ' ...
    'progress is outside the model.']);
disp(['Votes already observed are not rolled back. Restoring inputs in a ' ...
    'fresh call is a recovery target, not retry, election, or durable recovery.']);

%% Finish with checks and teach-back
disp(['Run run_checks, answer one interpretation prompt, then teach back ' ...
    'how vote timing, quorum size, intersection, timeout, and availability ' ...
    'shape safety and progress.']);
