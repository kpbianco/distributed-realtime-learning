%% P10 - Preserve Message Ordering
experimentFigureTag = 'P10ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the per-sender ordering mechanism
disp('What inputs, observable effects, and failure modes matter when you preserve Message Ordering?');
disp(['P09 showed one state version reaching replicas at different times. ' ...
    'P10 now sends six successive versions across paths with unequal delay.']);
disp(['Message k arrives at t_arrive(k) = t_send(k) + scale*d(k). ' ...
    'Arrival order can therefore differ from sender sequence order.']);
disp(['A strict receiver releases only the next expected sequence number and ' ...
    'holds later messages in a finite reorder buffer.']);
disp('This is per-sender order, not causal order, global total order, or consensus.');

%% Visualize the deterministic baseline timing view
baseline = model(1,2,100,true,true);
fprintf(['Baseline: raw arrival %s has %d inversions; strict delivery %s ' ...
    'completes at %.0f ms with %.0f message-ms of delivered holding.\n'], ...
    mat2str(baseline.arrivalSequence),baseline.arrivalInversionCount, ...
    mat2str(baseline.deliverySequence),baseline.completionTimeMs, ...
    baseline.totalOrderingHoldMessageMs);

figure('Name','P10 baseline send, arrival, and delivery timing', ...
    'Tag',experimentFigureTag);
plot(baseline.sequence,baseline.sendTimeMs,'o-', ...
    baseline.sequence,baseline.arrivalTimeMs,'s--', ...
    baseline.sequence,baseline.deliveryTimeBySequenceMs,'d-', ...
    'LineWidth',1.5);
grid on;
xlabel('Message sequence number (integer)');
ylabel('Time from batch start (ms)');
title('Baseline view 1: unequal path delay reorders arrival, not strict delivery');
legend({'Sender emission','Network arrival','Receiver delivery'}, ...
    'Location','best');

assert(isequal(baseline.sendTimeMs,[0 10 20 30 40 50]) && ...
    isequal(baseline.arrivalTimeMs,[20 15 55 35 65 50]) && ...
    isequal(baseline.arrivalSequence,[2 1 4 6 3 5]) && ...
    baseline.arrivalInversionCount == 4, ...
    'Baseline send or arrival ordering changed.');
assert(isequal(baseline.deliverySequence,1:6) && ...
    isequal(baseline.deliveryTimeBySequenceMs,[20 20 55 55 65 65]) && ...
    baseline.completeOrderedDelivery && baseline.finalStateVersion == 6, ...
    'Baseline strict delivery changed.');

%% Change the view to buffer occupancy and per-message holding
figure('Name','P10 baseline reorder-buffer cost', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
stairs(0:baseline.receivedMessageCount, ...
    [0 baseline.bufferOccupancyAfterEvent],'-o','LineWidth',1.5);
grid on;
xlabel('Network arrival event rank (integer)');
ylabel('Buffered successors (messages)');
title('Baseline view 2a: successors wait behind sequence gaps');
subplot(2,1,2);
bar(baseline.sequence,baseline.holdTimeBySequenceMs);
grid on;
xlabel('Message sequence number (integer)');
ylabel('Ordering hold before delivery (ms)');
title('Baseline view 2b: total delivered holding = 40 message-ms');

assert(isequal(baseline.bufferOccupancyAfterEvent,[1 0 1 2 1 0]) && ...
    baseline.reorderBufferHighWaterCount == 2 && ...
    isequal(baseline.holdTimeBySequenceMs,[0 5 0 20 0 15]) && ...
    baseline.totalOrderingHoldMessageMs == 40 && ...
    baseline.maxOrderingHoldMs == 20, ...
    'Baseline buffer or holding metric changed.');

%% Sweep 1: change only deterministic path-delay scale
delayScales = [0 0.5 1 2];
delaySweepArrivalInversions = zeros(size(delayScales));
delaySweepHoldingMessageMs = zeros(size(delayScales));
delaySweepCompletionMs = zeros(size(delayScales));
delaySweepBufferHighWater = zeros(size(delayScales));
for caseIndex = 1:numel(delayScales)
    current = model(delayScales(caseIndex),2,100,true,true);
    delaySweepArrivalInversions(caseIndex) = ...
        current.arrivalInversionCount;
    delaySweepHoldingMessageMs(caseIndex) = ...
        current.totalOrderingHoldMessageMs;
    delaySweepCompletionMs(caseIndex) = current.completionTimeMs;
    delaySweepBufferHighWater(caseIndex) = ...
        current.reorderBufferHighWaterCount;
end

figure('Name','P10 sweep 1 path-delay scale', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
plot(delayScales,delaySweepArrivalInversions,'o-', ...
    delayScales,delaySweepBufferHighWater,'s--','LineWidth',1.5);
grid on;
xlabel('Path-delay scale (x)');
ylabel('Inversions or buffered messages (count)');
title('Sweep 1: delay dispersion creates arrival inversions and buffering');
legend({'Raw arrival inversions','Buffer high-water mark'}, ...
    'Location','best');
subplot(2,1,2);
plot(delayScales,delaySweepHoldingMessageMs,'d-', ...
    'LineWidth',1.5);
grid on;
xlabel('Path-delay scale (x)');
ylabel('Delivered ordering hold (message-ms)');
title('Strict ordering trades added holding for monotonic state');

assert(isequal(delaySweepArrivalInversions,[0 2 4 4]) && ...
    isequal(delaySweepBufferHighWater,[0 1 2 2]) && ...
    isequal(delaySweepHoldingMessageMs,[0 7.5 40 110]) && ...
    isequal(delaySweepCompletionMs,[50 52.5 65 90]), ...
    'Path-delay sweep changed unexpectedly.');

%% Reset, then sweep 2: change only reorder-buffer capacity
bufferCapacities = [0 1 2];
capacitySweepDeliveredCount = zeros(size(bufferCapacities));
capacitySweepHighWater = zeros(size(bufferCapacities));
capacitySweepDecisionTimeMs = zeros(size(bufferCapacities));
capacitySweepCompleted = false(size(bufferCapacities));
for caseIndex = 1:numel(bufferCapacities)
    current = model(1,bufferCapacities(caseIndex),100,true,true);
    capacitySweepDeliveredCount(caseIndex) = ...
        current.deliveredMessageCount;
    capacitySweepHighWater(caseIndex) = ...
        current.reorderBufferHighWaterCount;
    capacitySweepCompleted(caseIndex) = ...
        current.completeOrderedDelivery;
    if current.completeOrderedDelivery
        capacitySweepDecisionTimeMs(caseIndex) = ...
            current.completionTimeMs;
    else
        capacitySweepDecisionTimeMs(caseIndex) = current.failureTimeMs;
    end
end

figure('Name','P10 sweep 2 reorder-buffer capacity', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
bar(bufferCapacities,[capacitySweepDeliveredCount(:), ...
    capacitySweepHighWater(:)]);
grid on;
xlabel('Reorder-buffer capacity (messages)');
ylabel('Messages (count)');
title('Sweep 2: capacity two preserves the complete six-message stream');
legend({'Delivered before decision','Buffer high-water mark'}, ...
    'Location','best');
subplot(2,1,2);
bar(bufferCapacities,capacitySweepDecisionTimeMs);
grid on;
xlabel('Reorder-buffer capacity (messages)');
ylabel('Completion or failure decision time (ms)');
title('Capacity zero/one fail closed; capacity two completes');

assert(isequal(capacitySweepDeliveredCount,[0 2 6]) && ...
    isequal(capacitySweepHighWater,[0 1 2]) && ...
    isequal(capacitySweepDecisionTimeMs,[15 50 65]) && ...
    isequal(capacitySweepCompleted,[false false true]), ...
    'Reorder-buffer-capacity sweep changed unexpectedly.');

%% Read the mechanism before the deliberately broken case
disp(['Sequence numbers do not accelerate any packet. They let the receiver ' ...
    'recognize a gap and hold successors instead of applying them early.']);
disp(['The finite buffer and gap deadline bound that holding. Exhausting either ' ...
    'resource stops delivery rather than silently crossing the gap.']);

%% Deliberately broken case: apply raw arrival order as sender order
broken = model(1,2,100,true,false);
figure('Name','P10 deliberately broken arrival-order assumption', ...
    'Tag',experimentFigureTag);
stairs(0:baseline.messageCount,baseline.stateVersionTrace,'o-', ...
    'LineWidth',1.5);
hold on;
stairs(0:broken.messageCount,broken.stateVersionTrace,'s--', ...
    'LineWidth',1.5);
hold off;
grid on;
xlabel('Applied message event count');
ylabel('Receiver state version (integer)');
title('Broken case: raw arrival order regresses version and finishes stale');
legend({'Strict sequence delivery','Raw arrival delivery'}, ...
    'Location','best');

assert(isequal(broken.deliverySequence,[2 1 4 6 3 5]) && ...
    broken.deliveryInversionCount == 4 && ...
    broken.stateRegressionCount == 2 && ...
    broken.finalStateVersion == 5 && ...
    ~broken.completeOrderedDelivery && ...
    broken.totalOrderingHoldMessageMs == 0, ...
    'Broken raw-arrival symptom changed.');
disp(['Broken assumption: arrival order is send order. Applying each arrival ' ...
    'immediately regresses the version twice and leaves version 5 after version 6.']);

%% Classify exact timeout, missing-message failure, rollback, and recovery
exactGapBoundary = model(1,2,20,true,true);
justBeforeGapBoundary = model(1,2,20 - 1e-12,true,true);
missingMessage = model(1,2,20,false,true);
capacityOverflow = model(1,1,100,true,true);
recoveryTarget = model(1,2,100,true,true);
assert(exactGapBoundary.completeOrderedDelivery && ...
    ~exactGapBoundary.timedOut);
assert(justBeforeGapBoundary.timedOut && ...
    justBeforeGapBoundary.timeoutExpectedSequence == 3 && ...
    justBeforeGapBoundary.deliveredMessageCount == 2);
assert(missingMessage.timedOut && ...
    missingMessage.failureTimeMs == 55 && ...
    isequal(missingMessage.deliverySequence,[1 2]) && ...
    missingMessage.remainingDeliverySuppressedAfterFailure && ...
    ~missingMessage.actualAsynchronousCancellationPerformed && ...
    ~missingMessage.rollbackModeled && ...
    missingMessage.deliveredPrefixNotRolledBack);
assert(capacityOverflow.bufferOverflow && ...
    capacityOverflow.failureTimeMs == 50 && ...
    capacityOverflow.rejectedSequence == 6 && ...
    isequal(capacityOverflow.deliverySequence,[1 2]));
assert(recoveryTarget.completeOrderedDelivery && ...
    isequal(recoveryTarget.deliverySequence,baseline.deliverySequence));
disp(['A message arriving exactly at its gap deadline is accepted; just before ' ...
    'that boundary, or with message 3 absent, delivery stops on prefix [1 2].']);
disp(['Stopping future delivery is finite event classification, not an actual ' ...
    'timer or asynchronous cancellation. Versions 1 and 2 are not rolled back.']);
disp(['Restoring the message/capacity in a fresh evaluation reaches the ordered ' ...
    'target; no retransmission, replay, or recovery protocol ran.']);

