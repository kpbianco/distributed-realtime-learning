%% P09 - Replicate Shared State
experimentFigureTag = 'P09ExperimentFigure';
existingFigures = findall(groot,'Type','figure','Tag',experimentFigureTag);
if ~isempty(existingFigures)
    close(existingFigures);
end

%% Read the replication mechanism
disp('What inputs, observable effects, and failure modes matter when you replicate Shared State?');
disp(['P08 coordinated one schedule activation. P09 starts after that point: ' ...
    'one accepted state update still reaches replicas at different times.']);
disp(['Mechanism: replica i applies at t_apply_i = scale*d_i + c_i; a W-ack ' ...
    'response occurs at the W-th online apply time, if it arrives by the timeout.']);
disp('The fixture sets acknowledgment-return delay to zero; no return transport or loss is modeled.');
disp('An acknowledgment threshold is not universal visibility, consensus, or message ordering.');

%% Visualize the deterministic baseline state timeline
baseline = model(1,4,0,true,160);
fprintf(['Baseline: W=%d responds at %.0f ms after all replicas apply version %d; ' ...
    'the slow-replica read returns %.0f%% at version %d.\n'], ...
    baseline.requiredAckCount,baseline.acknowledgmentLatencyMs, ...
    baseline.updateVersion,baseline.readValuePercent,baseline.readVersion);

timelineHorizonMs = baseline.ackTimeoutMs;
figure('Name','P09 baseline replica state timeline', ...
    'Tag',experimentFigureTag);
hold on;
for replicaIndex = 1:baseline.replicaCount
    applyTimeMs = baseline.nominalApplyTimeMs(replicaIndex);
    stairs([0 applyTimeMs timelineHorizonMs], ...
        [baseline.initialVersion baseline.updateVersion ...
        baseline.updateVersion] + 0.04 * (replicaIndex - 1), ...
        'LineWidth',2,'DisplayName',baseline.replicaLabels{replicaIndex});
end
xline(baseline.clientResponseTimeMs,'k--','W=4 response', ...
    'LineWidth',1.2,'HandleVisibility','off');
hold off; grid on;
xlabel('Time after primary accepts update (ms)');
ylabel('Applied state version (integer; traces offset for visibility)');
title('Baseline view 1: one version becomes visible at different times');
legend('Location','best');

assert(isequal(baseline.nominalApplyTimeMs,[0 15 35 75]) && ...
    baseline.acknowledgmentLatencyMs == 75 && ...
    baseline.currentReplicaCountAtResponse == 4 && ...
    baseline.readVersion == 1 && baseline.readYourWriteSatisfied, ...
    'Baseline apply times, acknowledgment, or read changed.');

%% Change the view to propagation and apply costs
figure('Name','P09 baseline propagation and apply costs', ...
    'Tag',experimentFigureTag);
bar(baseline.replicaIndex, ...
    [baseline.propagationDelayScale * ...
    baseline.basePropagationDelayMs(:),baseline.applyCostMs(:)], ...
    'stacked');
hold on;
yline(baseline.acknowledgmentLatencyMs,'k--','W=4 response', ...
    'LineWidth',1.2);
hold off; grid on;
xlabel('Replica');
ylabel('Time after primary accepts update (ms)');
title('Baseline view 2: transparent propagation plus apply cost');
set(gca,'XTick',baseline.replicaIndex, ...
    'XTickLabel',baseline.replicaLabels);
legend({'Propagation delay','Validation/apply cost','Write response'}, ...
    'Location','best');

assert(baseline.convergenceTimeMs == 75 && ...
    baseline.allReplicaLagExposureReplicaMs == 125 && ...
    baseline.allReplicasCurrentAtResponse, ...
    'Baseline convergence or lag exposure changed.');

%% Sweep 1: change only propagation delay scale
propagationDelayScales = [0.5 1 2];
delaySweepAckMs = zeros(size(propagationDelayScales));
delaySweepConvergenceMs = zeros(size(propagationDelayScales));
delaySweepLagExposureReplicaMs = zeros(size(propagationDelayScales));
for caseIndex = 1:numel(propagationDelayScales)
    current = model(propagationDelayScales(caseIndex),4,0,true,160);
    delaySweepAckMs(caseIndex) = current.acknowledgmentLatencyMs;
    delaySweepConvergenceMs(caseIndex) = current.convergenceTimeMs;
    delaySweepLagExposureReplicaMs(caseIndex) = ...
        current.allReplicaLagExposureReplicaMs;
end

figure('Name','P09 sweep 1 propagation delay', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
plot(propagationDelayScales,delaySweepAckMs,'o-', ...
    propagationDelayScales,delaySweepConvergenceMs,'s--', ...
    'LineWidth',1.5); grid on;
xlabel('Propagation delay scale (x)');
ylabel('Time after primary accepts update (ms)');
title('Sweep 1: delay stretches response and convergence');
legend({'W=4 acknowledgment','All-replica convergence'}, ...
    'Location','best');
subplot(2,1,2);
plot(propagationDelayScales,delaySweepLagExposureReplicaMs, ...
    'd-','LineWidth',1.5); grid on;
xlabel('Propagation delay scale (x)');
ylabel('Accumulated version lag (replica-ms)');
title('Longer propagation leaves more replica-time on version 0');

assert(isequal(delaySweepAckMs,[40 75 145]) && ...
    isequal(delaySweepConvergenceMs,[40 75 145]) && ...
    isequal(delaySweepLagExposureReplicaMs,[70 125 235]), ...
    'Propagation-delay sweep changed unexpectedly.');

%% Reset, then sweep 2: change only acknowledgment count
requiredAckCounts = [1 2 4];
ackSweepLatencyMs = zeros(size(requiredAckCounts));
ackSweepCurrentReplicaCount = zeros(size(requiredAckCounts));
ackSweepSlowReadVersion = zeros(size(requiredAckCounts));
for caseIndex = 1:numel(requiredAckCounts)
    current = model(1,requiredAckCounts(caseIndex),0,true,160);
    ackSweepLatencyMs(caseIndex) = current.acknowledgmentLatencyMs;
    ackSweepCurrentReplicaCount(caseIndex) = ...
        current.currentReplicaCountAtResponse;
    ackSweepSlowReadVersion(caseIndex) = current.readVersion;
end

figure('Name','P09 sweep 2 acknowledgment count', ...
    'Tag',experimentFigureTag);
subplot(2,1,1);
bar(requiredAckCounts,ackSweepLatencyMs); grid on;
xlabel('Required acknowledgments W (count)');
ylabel('Write response latency (ms)');
title('Sweep 2: more acknowledgments delay the response');
subplot(2,1,2);
bar(requiredAckCounts, ...
    [ackSweepCurrentReplicaCount(:),ackSweepSlowReadVersion(:)]); grid on;
xlabel('Required acknowledgments W (count)');
ylabel('Count or version (integer)');
title('Visibility at response: current replicas and Replica D version');
legend({'Current replicas','Replica D read version'},'Location','best');

assert(isequal(ackSweepLatencyMs,[0 15 75]) && ...
    isequal(ackSweepCurrentReplicaCount,[1 2 4]) && ...
    isequal(ackSweepSlowReadVersion,[0 0 1]), ...
    'Acknowledgment-count sweep changed unexpectedly.');

%% Read the mechanism before the deliberately broken case
disp(['A smaller W returns sooner because it waits for fewer apply events. ' ...
    'It does not prove that an arbitrary replica already exposes the update.']);
disp(['The consistency window ends only when the selected read replica applies ' ...
    'the version, or the read is routed to a replica known to be current.']);

%% Deliberately broken case: treat W=1 as universal visibility
broken = model(1,1,0,true,160);
figure('Name','P09 deliberately broken universal-visibility assumption', ...
    'Tag',experimentFigureTag);
bar(broken.replicaIndex,broken.replicaVersionAtResponse); grid on;
xlabel('Replica');
ylabel('Applied state version at client response (integer)');
title('Broken case: primary acknowledged, slow replica still returns version 0');
set(gca,'XTick',broken.replicaIndex, ...
    'XTickLabel',broken.replicaLabels);

assert(broken.writeAcknowledged && ...
    broken.clientResponseTimeMs == 0 && ...
    isequal(broken.replicaVersionAtResponse,[1 0 0 0]) && ...
    broken.readVersion == 0 && broken.staleReadObserved && ...
    ~broken.readYourWriteSatisfied && ...
    strcmp(broken.outcome,'acknowledged-stale-read'), ...
    'Broken stale-read symptom changed.');
disp(['Broken assumption: acknowledgment threshold is not universal visibility. ' ...
    'W=1 confirms only the primary apply, so Replica D still returns 40%/version 0.']);

%% Classify timeout, partial apply, and stateless recovery
timedOut = model(1,4,0,false,100);
recoveryTarget = model(1,4,0,true,160);
assert(timedOut.ackTimedOut && ...
    timedOut.currentReplicaCountAtResponse == 3 && ...
    timedOut.partialApplyAtResponse && ...
    timedOut.writeMayHaveAppliedDespiteTimeout && ...
    ~timedOut.readSucceeded && ~timedOut.actualWaitPerformed && ...
    ~timedOut.rollbackModeled && ~timedOut.actualRollbackPerformed, ...
    'Timeout or partial-apply classification changed.');
assert(recoveryTarget.writeAcknowledged && ...
    recoveryTarget.convergenceReached && ...
    recoveryTarget.readVersion == 1, ...
    'Restored-replica recovery fixture did not converge.');
disp(['With Replica D offline, W=4 reaches the 100 ms timeout after A-C already applied. ' ...
    'That is an arithmetic classification: nothing waited and no partial apply was rolled back.']);
disp(['Restoring Replica D and reevaluating the deterministic fixture converges at 75 ms. ' ...
    'A real catch-up, retry, deduplication, or recovery protocol is outside this model.']);

